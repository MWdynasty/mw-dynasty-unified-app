'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const {createRequire}=require('node:module');
const sandbox={module:{exports:{}},require:createRequire(require('node:path').resolve('server/api/coach/performance.js')),console};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('server/api/coach/performance.js','utf8')+'\nmodule.exports={sprintSession,summarizeAthlete};',sandbox);
const {sprintSession,summarizeAthlete}=sandbox.module.exports;
const rows=[3.38,3.47,4.07,3.87,3.95].map((t,i)=>({athlete_id:'a',workout_key:'current',program_week:1,program_day:2,rep_number:i+1,distance_m:30,actual_seconds:t,target_seconds:null,result_status:'finished',entry_source:'coach',recorded_at:'2026-10-06T15:56:06Z'}));
const session=r=>sprintSession({workout_key:'current',program_week:1,program_day:2,latest:r[0]?.recorded_at,rows:r},null);
const live=session(rows);
assert.equal(live.rep_count,5);
assert.equal(live.execution_score_pct,null,'missing targets must not invent a pace score');
assert.equal(live.comparison_basis,'actual_times');
assert.equal(live.consistency_score,92.7);
assert.equal(live.first_to_last_dropoff_pct,16.9);
assert.equal(live.session_rpe,null);
assert.equal(session(rows.slice(0,1)).consistency_score,null,'one rep cannot establish consistency');
assert.equal(session(rows.map((r,i)=>({...r,distance_m:i?60:30}))).consistency_score,null,'unlike distances cannot compare raw times');
assert.equal(session(rows.map(r=>({...r,distance_m:null}))).first_to_last_dropoff_pct,null,'unknown distances cannot compare raw times');
const dnf=session([...rows,{...rows[0],rep_number:6,actual_seconds:99,result_status:'dnf'}]);
assert.equal(dnf.rep_count,5);assert.equal(dnf.consistency_score,live.consistency_score);
const targeted=rows.map(r=>({...r,target_seconds:3.62,pace_status:r.rep_number===1?'on_pace':'outside_target'}));
assert.equal(session(targeted).execution_score_pct,20);
assert.equal(session(targeted).comparison_basis,'target_ratios');
assert.equal(session(targeted).consistency_score,live.consistency_score);
assert.equal(session(targeted).first_to_last_dropoff_pct,live.first_to_last_dropoff_pct);
const strength=[1,2].map(d=>({athlete_id:'a',program_week:1,strength_day:d,lifecycle_status:'completed',status:'as_prescribed',session_feel:'normal',completed_at:'2026-10-05T12:00:00Z'}));
const summary=summarizeAthlete('a',rows,[],[],strength);
assert.equal(summary.strength.combined_signal,'insufficient_shared_data','null sprint score must not be treated as zero');
const old=rows.map(r=>({...r,workout_key:'previous',recorded_at:'2026-09-29T12:00:00Z'}));
assert.equal(summarizeAthlete('a',[...rows,...old],[],[],[]).sprint.session_count,2,'same week/day in different workout identities stays separate');
console.log('PASS: no-target coach reps populate comparable consistency/drop-off without invented pace/RPE, DNF contamination, mixed-distance comparisons, or merging separate workout identities.');
