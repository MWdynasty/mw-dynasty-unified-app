const fs=require('node:fs');
const assert=require('node:assert/strict');
const source=fs.readFileSync('coach/app-live-20261005-r1.js','utf8');
const start=source.indexOf('function mwCoachInsightSummary('),end=source.indexOf('async function insightsPage',start);
assert.ok(start>=0&&end>start);
const summarize=new Function(source.slice(start,end)+';return mwCoachInsightSummary;')();
const roster=[{id:'a',name:'Athlete A'},{id:'b',name:'Athlete B'}];
const records=[{athlete_id:'a',sprint:{session_count:3,trend:'improving',latest:{execution_score_pct:80}},strength:{session_count:2,max_progression:{changes:{front_squat:{delta:10}}}},flags:[{level:'watch',message:'Review fatigue'}]},{athlete_id:'outside',sprint:{session_count:9,latest:{execution_score_pct:99}},strength:{session_count:9},flags:[{level:'attention',message:'Outside roster'}]}];
const x=summarize(roster,records,true);
assert.equal(x.sprintCount,1);
assert.equal(x.strengthCount,1);
assert.equal(x.executionMean,80);
assert.equal(x.improvingExecution,1);
assert.equal(x.strengthProgress,1);
assert.equal(x.flags.length,1);
assert.equal(x.flags[0].athleteId,'a');
assert.equal(x.mismatch,true);
const empty=summarize([],records,true);
assert.equal(empty.sprintCount,0);
assert.equal(empty.strengthCount,0);
assert.equal(empty.flags.length,0);
assert.equal(empty.executionMean,null);
const limited=summarize(roster,records,false);
assert.equal(limited.sprintCount,0);
assert.equal(limited.executionMean,null);
assert.equal(limited.strengthCount,1);
assert.ok(source.includes("tile('Athlete Development'"));
assert.ok(source.includes("tile('Training Effectiveness'"));
assert.ok(source.includes("tile('Coach Priorities'"));
console.log('PASS: Coach Performance Intelligence roster-scoped metrics, tier gating and three-section dashboard');
