const assert=require('node:assert/strict');
const fs=require('node:fs');
const host='motion-staging.mwdynasty.com';
const read=p=>fs.readFileSync(p,'utf8');
const swift=read('ios_v3_0_16_patch/MWDynasty/WebViewController.swift');
const plist=read('ios_v3_0_16_patch/MWDynasty/Info.plist');
const workflow=read('codemagic.yaml');
const release=read('ios_v3_0_16_patch/Config/Release.xcconfig');
const athlete=read('athlete/index.html');
const coach=read('coach/index.html');
assert.ok(swift.includes(host),'Native staging host must be pinned');
assert.ok(swift.includes('isMotionPilotBuild'));
assert.ok(swift.includes('isAuthorizedWebHost(url)'));
assert.ok(swift.includes('!isMotionPilotBuild'),'No StoreKit bridging in pilot');
assert.ok(swift.includes('url.host == "app.mwdynasty.com"'),'Normal production remains restricted');
assert.ok(plist.includes(host+'/athlete/motion?motionPilot=1'));
assert.ok(plist.includes('<key>MWMotionPilotTestFlight</key>'));
assert.ok(workflow.includes('testflight-motion-intelligence'));
assert.ok(workflow.includes('MW_PILOT="false"'));
assert.ok(workflow.includes('MW_PILOT="true"'));
assert.ok(workflow.includes('submit_to_testflight: true'));
assert.ok(release.includes('MARKETING_VERSION = 3.0.17'));
assert.ok(release.includes('CURRENT_PROJECT_VERSION = 16'));
assert.ok(read('ios_v3_0_16_patch/MWDynasty.xcodeproj/project.pbxproj').includes('CURRENT_PROJECT_VERSION = 16;'),'Xcode must not override the requested build number');
assert.ok(read('ios_v3_0_16_patch/MWDynasty.xcodeproj/project.pbxproj').includes('MARKETING_VERSION = 3.0.17;'));
assert.ok(athlete.includes('COACH MOTION INTELLIGENCE TEST'));
assert.ok(coach.includes('motionPilot=1'));
console.log('Isolated Motion TestFlight 3.0.17(16) configuration and production protection passed.');
