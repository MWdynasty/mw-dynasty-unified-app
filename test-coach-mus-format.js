'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const app=fs.readFileSync('coach/app-live-20261005-r1.js','utf8');
const start=app.indexOf('function mwCoachFormatReply('),end=app.indexOf('function coachMWPage(){',start);
assert.ok(start>=0&&end>start);
const escape=x=>String(x).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const format=new Function('escapeHtml',app.slice(start,end)+';return mwCoachFormatReply;')(escape);
const output=format('### Running the 200m curve\n- Choose a **smooth path**.\n- Relax.\n\n### Boomerang effect\nKeep your **rhythm**.');
assert.match(output,/<h3>Running the 200m curve<\/h3>/);
assert.match(output,/<ul><li>Choose a <strong>smooth path<\/strong>\.<\/li><li>Relax\.<\/li><\/ul>/);
assert.match(output,/<h3>Boomerang effect<\/h3>/);
assert.match(output,/<p>Keep your <strong>rhythm<\/strong>\.<\/p>/);
const hostile=format('<img src=x onerror=alert(1)>\n**bold**');
assert.doesNotMatch(hostile,/<img/);
assert.match(hostile,/&lt;img/);
assert.match(hostile,/<strong>bold<\/strong>/);
assert.match(app,/m\.role==='assistant'\?mwCoachFormatReply\(m\.content\)/);
assert.match(app,/body\.innerHTML=mwCoachFormatReply\(content\)/);
console.log('PASS: Coach Mus formats both saved and live messages, escaping unsafe HTML');
