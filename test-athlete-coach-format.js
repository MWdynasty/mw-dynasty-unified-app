'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const source=fs.readFileSync('assets/mw-native.js','utf8');
const start=source.indexOf('function formatCoachReply(input){');
const end=source.indexOf('window.MWAthleteCoachReplyFormat',start);
assert.ok(start>=0&&end>start,'Athlete Coach MW format hook exists');
const escapeText=value=>String(value).replace(/[&<>"']/g,ch=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[ch]));
const format=new Function('escapeText',source.slice(start,end)+';return formatCoachReply;')(escapeText);
const formatted=format('### Running the curve\n- Run a **smooth, controlled line**.\n- Stay relaxed.\n\n### Boomerang effect\nKeep your **rhythm**.');
assert.match(formatted,/<h3>Running the curve<\/h3>/);
assert.match(formatted,/<li>Run a <strong>smooth, controlled line<\/strong>\.<\/li>/);
assert.match(formatted,/<h3>Boomerang effect<\/h3>/);
assert.match(formatted,/<strong>rhythm<\/strong>/);
const unsafe=format('<img src=x onerror=alert(1)>\n**safe**');
assert.doesNotMatch(unsafe,/<img/);
assert.match(unsafe,/&lt;img/);
assert.match(unsafe,/<strong>safe<\/strong>/);
assert.match(source,/querySelectorAll\('\.msg\.coach'\)/);
assert.match(source,/MutationObserver/);
assert.match(source,/dataset\.mwReplyFormatted/);
assert.match(source,/message\.querySelector\('button,input,textarea,select,img,video,audio,a'\)/);
assert.match(source,/location\.pathname\.startsWith\('\/athlete'\)/);
console.log('PASS: athlete Coach MW reply formatting, unsafe HTML escaping and live message observer');